WRONG_PLACES = [
    "la gare centrale",
    "le parking souterrain",
    "la poste principale",
    "le musée fermé",
    "la piscine vide",
]


def lesson(
    lesson_title: str,
    theme: str,
    activities: list[str],
    items: list[str],
    benefits: list[str],
    warnings: list[str],
    wrong_activities: list[str],
    wrong_items: list[str],
    wrong_benefits: list[str],
) -> dict:
    for label, values in {
        "activities": activities,
        "items": items,
        "benefits": benefits,
        "warnings": warnings,
    }.items():
        assert len(values) == 20, f"{lesson_title}: {label} has {len(values)} entries"
    return build_lesson(
        {
            "lesson": lesson_title,
            "theme": theme,
            "activities": activities,
            "items": items,
            "benefits": benefits,
            "warnings": warnings,
            "wrong_places": WRONG_PLACES,
            "wrong_activities": wrong_activities,
            "wrong_items": wrong_items,
            "wrong_benefits": wrong_benefits,
        }
    )


